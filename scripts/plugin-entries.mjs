// Writes packages/compiler/plugins: the entry points through which a project names the feature plugins the compiler
// package ships, such as `ts-plus-plus/plugins/modern-syntax` in tsppconfig.json and
// `ts-plus-plus/plugins/formal-verification/smt` in an import. Each entry forwards to the plugin's own package, an
// internal one that is never published, and one exists for every entry of that package's `exports`.
// Usage: node scripts/plugin-entries.mjs [--check]
import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const compiler = path.join(root, "packages", "compiler");
const output = path.join(compiler, "plugins");
const scope = "@tspp/plugin-";

/**
 * The project-facing name of a plugin package or one of its subpaths: `@tspp/plugin-modern-syntax` →
 * `ts-plus-plus/plugins/modern-syntax`, `@tspp/plugin-formal-verification/smt` → `ts-plus-plus/plugins/formal-verification/smt`.
 */
export function pluginEntryName(specifier) {
    if (!specifier.startsWith(scope)) throw new Error(`${specifier} is not a plugin package.`);
    return `ts-plus-plus/plugins/${specifier.slice(scope.length)}`;
}

/** The plugin packages the compiler package ships: its dependencies other than the SDK. */
export function shippedPluginPackages() {
    const manifest = JSON.parse(fs.readFileSync(path.join(compiler, "package.json"), "utf8"));
    return Object.keys(manifest.dependencies ?? {}).filter(name => name.startsWith(scope) && name !== "@tspp/plugin-sdk").sort();
}

/** Every file of packages/compiler/plugins, by its path relative to that directory. */
export function pluginEntryFiles() {
    const files = new Map();
    for (const packageName of shippedPluginPackages()) {
        const manifest = JSON.parse(fs.readFileSync(path.join(root, "packages", "plugins", packageName.slice(scope.length), "package.json"), "utf8"));
        const subpaths = Object.keys(manifest.exports ?? { ".": "" }).filter(key => key !== "./package.json");
        for (const subpath of subpaths) {
            const target = subpath === "." ? packageName : `${packageName}/${subpath.slice(2)}`;
            const entry = pluginEntryName(target).slice("ts-plus-plus/plugins/".length);
            // Only a plugin's main entry has a default export: the plugin itself.
            const declaration = subpath === "."
                ? [`export * from "${target}";`, `export { default } from "${target}";`]
                : [`export * from "${target}";`];
            files.set(`${entry}.js`, ["\"use strict\";", `module.exports = require("${target}");`]);
            files.set(`${entry}.d.ts`, declaration);
        }
    }
    const header = "// Generated by scripts/plugin-entries.mjs; edit that script instead.";
    return new Map([...files].sort(([a], [b]) => a.localeCompare(b)).map(([file, lines]) => [file, [header, ...lines, ""].join("\r\n")]));
}

function existingFiles(directory, prefix = "") {
    if (!fs.existsSync(directory)) return [];
    return fs.readdirSync(directory, { withFileTypes: true }).flatMap(entry =>
        entry.isDirectory()
            ? existingFiles(path.join(directory, entry.name), `${prefix}${entry.name}/`)
            : [`${prefix}${entry.name}`]
    );
}

function main() {
    const expected = pluginEntryFiles();
    const stale = existingFiles(output).filter(file => !expected.has(file));
    const changed = [...expected].filter(([file, text]) => {
        const full = path.join(output, file);
        return !fs.existsSync(full) || fs.readFileSync(full, "utf8") !== text;
    }).map(([file]) => file);
    if (process.argv.includes("--check")) {
        if (stale.length || changed.length) {
            console.error(`packages/compiler/plugins is out of date (${[...changed, ...stale].join(", ")}). Run node scripts/plugin-entries.mjs.`);
            process.exit(1);
        }
        return;
    }
    for (const file of stale) fs.rmSync(path.join(output, file));
    for (const file of changed) {
        fs.mkdirSync(path.dirname(path.join(output, file)), { recursive: true });
        fs.writeFileSync(path.join(output, file), expected.get(file));
    }
    console.log(`packages/compiler/plugins: ${changed.length} written, ${stale.length} removed.`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
